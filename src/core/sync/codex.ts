import { AgentForgeConfig, SyncOutput } from './types';

export function generateCodexRules(config: AgentForgeConfig): SyncOutput {
  const lines: string[] = [
    `# AGENTS.md - Project Directives for OpenAI Codex`,
    `# Generated by AgentForge (https://github.com/mrzroot/agentforge)`,
    ``,
    `## Project Overview: ${config.name}`,
    `${config.description || 'AI-assisted modern codebase.'}`,
    ``,
    `## Commands & Environment`,
    `- Build: \`npm run build\` (or equivalent)`,
    `- Test: \`${config.stack?.testRunner || 'npm test'}\``,
    `- Languages: ${(config.stack?.languages || ['TypeScript']).join(', ')}`,
    ``,
    `## Engineering Rules`,
    ...config.rules.core.map(r => `- ${r}`),
    ``
  ];

  if (config.rules.architecture?.length) {
    lines.push(`## Architecture`, ...config.rules.architecture.map(r => `- ${r}`), ``);
  }
  if (config.rules.security?.length) {
    lines.push(`## Security`, ...config.rules.security.map(r => `- ${r}`), ``);
  }
  if (config.rules.testing?.length) {
    lines.push(`## Testing`, ...config.rules.testing.map(r => `- ${r}`), ``);
  }
  if (config.rules.git?.length) {
    lines.push(`## Git Conventions`, ...config.rules.git.map(r => `- ${r}`), ``);
  }

  return {
    agent: 'codex',
    files: [
      {
        path: 'AGENTS.md',
        content: lines.join('\n'),
        action: 'created'
      }
    ]
  };
}
